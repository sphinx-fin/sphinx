#!/bin/sh
# 갱신된 인증서를 nginx 가 다시 읽게 한다. 소유: 오준서
#
# ── 왜 이게 필요한가 ────────────────────────────────────────────────────────
#
# certbot 컨테이너가 갱신을 하지만 **nginx 는 기동 때 읽은 인증서를 계속 쓴다.** 파일이
# 바뀌어도 알아채지 않으므로, 갱신에 성공해도 브라우저에는 만료된 인증서가 그대로 나간다.
# 그 실패는 90일 뒤에, 아무도 안 보고 있을 때 온다.
#
# certbot 의 `--deploy-hook` 은 **자기 컨테이너 안에서** 돈다. 거기서 nginx 를 reload 하려면
# 도커 소켓을 붙여 줘야 하는데, 그건 컨테이너 하나에 호스트 전체 권한을 주는 것이라 안 한다
# (`#41` 이 세운 방향과 정반대다).
#
# 그래서 반대로 **nginx 쪽이 주기적으로 자기를 reload 한다.** reload 는 워커를 새로 띄우고
# 기존 연결은 끝날 때까지 두는 무중단 동작이라, 필요 없을 때 돌아도 손해가 없다.
set -eu

# 인증서가 없으면 443 자체가 없다(20-tls.sh). reload 할 이유도 없다.
[ -n "${SPHINX_PUBLIC_HOST:-}" ] || exit 0
[ -f "/etc/letsencrypt/live/${SPHINX_PUBLIC_HOST}/fullchain.pem" ] || exit 0

# ❗백그라운드로 띄우고 **바로 빠진다.** 공식 엔트리포인트는 이 디렉토리의 스크립트가 전부
# 끝나야 nginx 를 exec 하므로, 여기서 기다리면 컨테이너가 영원히 안 뜬다.
(
    # 첫 reload 는 12시간 뒤다. 기동 직후는 방금 읽었으므로 할 일이 없다.
    while :; do
        sleep 12h
        # nginx 가 아직 안 떴거나 내려가는 중이면 조용히 넘어간다 — 여기서 죽어도
        # 알려 줄 곳이 없고, 다음 주기에 다시 시도한다.
        nginx -s reload 2>/dev/null || true
    done
) &

echo "인증서 reload 타이머 시작 — 12시간마다 nginx -s reload"
