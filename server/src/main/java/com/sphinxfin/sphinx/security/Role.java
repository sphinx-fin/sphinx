package com.sphinxfin.sphinx.security;

/**
 * F-CMN-002 역할 정의. 소유: 정세현
 *
 * ── 영업 조직 역할 부재 원칙 (기능명세서 0.4, ADR-001) ────────────────
 * 이해도 데이터 접근 권한을 부여할 수 있는 역할 자체를 만들지 않는다.
 * 권한을 주지 않는 것과 줄 수 있는 대상이 없는 것은, 운영 압박이 들어왔을 때
 * 전혀 다르게 작동한다. 역할이 없으면 부여하려면 코드를 고쳐야 하고 PR에 남는다.
 *
 * 따라서 본부 영업·마케팅 조직에 대응하는 상수는 이 enum에 없다 — 누락이 아니라
 * 설계다. 추가하려면 ADR-001과 기획서 7-4를 함께 반박해야 한다.
 *
 * 주의: SELLER(판매 직원)와 영업 조직은 다른 것이다. SELLER는 창구에서 세션을
 * 진행하고 판정 결과(S-05)를 확인하는 주체이므로 유지한다. 차단 대상은 집계된
 * 이해도 데이터를 소비할 수 있는 본부 영업·마케팅 조직이다.
 *
 * 역할 목록만으로는 부족하다 — 실제 차단은 rbac_policy.yaml의 데이터 범위
 * 분리가 만든다. 역할만 지우고 범위를 나누지 않으면 SELLER 권한으로 대시보드가
 * 열려 같은 구멍이 난다.
 * ────────────────────────────────────────────────────────────────────
 */
public enum Role {
    /** 고객 — 본인 세션의 인터뷰 응답(S-03), 교부용 리포트 요약 수령. 그 외 일체 접근 불가 */
    CUST,
    /** 판매 직원 — 세션 진행, 본인이 진행한 세션의 판정 결과(S-05). 집계 접근 불가 */
    SELLER,
    /** 지점 관리자 — 적색 오버라이드 승인(F-GTE-002), 자기 지점 범위. 한계는 ADR-002 */
    MGR,
    /** 준법감시 — 전체 범위. 집계(오해 지도·선행지표), 감사 로그, 오버라이드 자동 통보 수신 */
    COMPL,
    /** 시스템 관리자 — 계정·역할 배정과 설정에 한정. 세션·집계 데이터는 읽지 않는다 (ADR-001) */
    ADMIN
}
