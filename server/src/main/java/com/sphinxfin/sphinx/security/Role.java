package com.sphinxfin.sphinx.security;

/**
 * F-CMN-002 역할 정의. 소유: 정세현
 *
 * ── 영업 조직 역할 부재 원칙 (명세서 0.4) ──────────────────────────────
 * "이해도 데이터 접근 권한을 부여할 수 있는 역할 자체를 만들지 않는 것이
 *  역이용 방지 요건의 구현이다."
 *
 * 권한을 주지 않는 것이 아니라, 줄 수 있는 대상을 없앤다. 역할이 존재하면
 * 언젠가 "이번만 조회 권한 주자"가 정책 수정으로 가능해진다. 역할이 없으면
 * 코드를 고쳐야 하고, 그것은 PR에 남는다.
 *
 * 따라서 본부 영업·마케팅 조직에 대응하는 상수는 이 enum에 없다 — 누락이 아니라
 * 설계다. 추가하려면 이 주석과 기획서 7-4를 함께 반박해야 한다.
 *
 * 주의: SELLER(창구 판매 직원)와 영업 조직은 다른 것이다. SELLER는 세션을
 * 진행하고 S-05 판정 결과를 봐야 하는 주체이므로 반드시 존재한다. 차단 대상은
 * 이해도 집계를 받아 타겟팅에 쓸 수 있는 쪽, 즉 본부 영업·마케팅이다.
 *
 * 역할 목록만으로는 부족하다 — 실제 차단은 rbac_policy.yaml의 데이터 범위
 * (scope) 분리가 만든다. SELLER는 개별 세션에만, 집계는 COMPL만.
 * ────────────────────────────────────────────────────────────────────
 */
public enum Role {
    /** 창구 판매 직원 — 세션 진행, 본인이 진행한 개별 세션의 판정 결과(S-05) 조회. 집계 접근 불가 */
    SELLER,
    /** 지점 관리자 — 적색 오버라이드 승인(F-GTE-002), 소속 지점 범위로 한정. 한계는 ADR-0002 */
    MGR,
    /** 준법감시 — 집계(오해 지도·선행지표) 접근, 감사 로그 조회. 오버라이드 자동 통보 수신 */
    COMPL,
    /** 감사 — 읽기 전용. 해시 체인 검증 권한 포함 */
    AUDITOR
}
